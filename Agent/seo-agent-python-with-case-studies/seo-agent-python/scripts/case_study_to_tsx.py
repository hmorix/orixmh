def slugify(text):
    text = (text or "").lower().strip()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-") or "case-study"


def component_name_for(slug):
    parts = re.split(r"[-_]+", slug)
    name = "".join(p.capitalize() for p in parts if p)
    return f"{name or 'CaseStudy'}Page"


def _to_camel(record):
    return {
        "title": record.get("title"),
        "slug": record.get("slug"),
        "excerpt": record.get("excerpt"),
        "category": record.get("category") or "Case Study",
        "content": record.get("content") or [],
        "readTime": record.get("read_time"),
        "publishedAt": record.get("published_at"),
        "isDemo": bool(record.get("is_demo", True)),
        "clientName": record.get("client_name"),
        "industry": record.get("industry"),
        "companySize": record.get("company_size"),
        "location": record.get("location"),
        "serviceUsed": record.get("service_used"),
        "timeline": record.get("timeline"),
        "results": record.get("results") or [],
        "hasTestimonial": bool(record.get("testimonial_quote")),
        "testimonialQuote": record.get("testimonial_quote"),
        "testimonialAuthor": record.get("testimonial_author"),
        "testimonialRole": record.get("testimonial_role"),
        "heroImageUrl": record.get("hero_image_url"),
        "galleryImages": record.get("gallery_images") or [],
        "ctaText": record.get("cta_text") or "Ready to build something like this?",
        "ctaUrl": record.get("cta_url") or "/contact",
        "referenceLinks": record.get("reference_links") or [],
        "seoTitle": record.get("seo_title"),
        "metaDescription": record.get("meta_description"),
        "canonicalUrl": record.get("canonical_url"),
        "openGraph": record.get("open_graph"),
        "twitterCard": record.get("twitter_card"),
        "breadcrumbs": record.get("breadcrumbs") or [],
        "schemaJsonld": record.get("schema_jsonld"),
        "wordCount": record.get("word_count"),
    }


def generate_case_study_page(record):
    slug = slugify(record.get("slug") or record.get("title"))
    component_name = component_name_for(slug)
    data_json = json.dumps(_to_camel(record), indent=2, ensure_ascii=False)

    tsx = (
        COMPONENT_TEMPLATE.replace(_TOKEN_SLUG, slug)
        .replace(_TOKEN_DATA_JSON, data_json)
        .replace(_TOKEN_COMPONENT_NAME, component_name)
    )

    os.makedirs(OUTPUT_DIR, exist_ok=True)
    out_path = os.path.join(OUTPUT_DIR, f"{slug}.tsx")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(tsx)

    _update_registry()
    _update_index(record, slug)

    return slug, out_path


def _update_registry():
    if not os.path.isdir(OUTPUT_DIR):
        return
    slugs = sorted(
        f[:-4] for f in os.listdir(OUTPUT_DIR) if f.endswith(".tsx") and f != "registry.ts"
    )
    lines = [
        "// AUTO-GENERATED by scripts/case_study_to_tsx.py — do not edit by hand.",
        "// Maps slug -> lazily-loaded static case study page component.",
        "import { lazy } from 'react'",
        "",
        "export const caseStudyPageRegistry: Record<string, ReturnType<typeof lazy>> = {",
    ]
    for slug in slugs:
        lines.append(f"  '{slug}': lazy(() => import('./{slug}')),")
    lines.append("}")
    with open(REGISTRY_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def _update_index(record, slug):
    """Lightweight index for a /case-studies listing page + dashboard stats."""
    index = {}
    if os.path.exists(INDEX_FILE):
        try:
            with open(INDEX_FILE, "r", encoding="utf-8") as f:
                for item in json.load(f):
                    index[item["slug"]] = item
        except (json.JSONDecodeError, KeyError):
            index = {}

    index[slug] = {
        "slug": slug,
        "title": record.get("title"),
        "excerpt": record.get("excerpt"),
        "clientName": record.get("client_name"),
        "industry": record.get("industry"),
        "isDemo": bool(record.get("is_demo", True)),
        "canonicalUrl": record.get("canonical_url"),
        "publishedAt": record.get("published_at"),
        "wordCount": record.get("word_count"),
    }

    os.makedirs(os.path.dirname(INDEX_FILE), exist_ok=True)
    ordered = sorted(index.values(), key=lambda p: p.get("publishedAt") or "", reverse=True)
    with open(INDEX_FILE, "w", encoding="utf-8") as f:
        json.dump(ordered, f, indent=2, ensure_ascii=False)


def main():
    if len(sys.argv) < 2:
        print("Usage: python scripts/case_study_to_tsx.py <path-to-record.json>")
        sys.exit(1)
    with open(sys.argv[1], "r", encoding="utf-8") as f:
        record = json.load(f)
    slug, out_path = generate_case_study_page(record)
    from scripts.sync_frontend_content import sync_frontend_content

    sync_frontend_content()
    print(f"[case-study-to-tsx] Generated {out_path} (slug: {slug})")


if __name__ == "__main__":
    main()
