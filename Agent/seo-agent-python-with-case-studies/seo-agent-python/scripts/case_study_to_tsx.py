# Converts a case-study JSON record (the same shape workflows/case_study_pipeline.py
# produces) into a standalone, statically-baked TSX page component. Same
# pattern as scripts/json_to_tsx.py for blog posts, extended with:
#   - a hero/poster image area (1200x630-ratio placeholder if no image yet)
#   - a client meta strip (industry / company size / timeline / service)
#   - a results grid (from the `results` array — placeholders render with a
#     visibly muted "placeholder" style so they're never mistaken for real
#     published numbers)
#   - a photo gallery grid
#   - a testimonial block (only rendered if hasTestimonial-equivalent data exists)
#   - a CTA section
#
# Usage (usually called by workflows/case_study_publish.py, not run directly):
#   python scripts/case_study_to_tsx.py path/to/case-study-record.json
